#!/usr/bin/env node

const args = parseArgs(process.argv.slice(2));
const apiBaseUrl = args.apiBaseUrl || process.env.API_BASE_URL || 'http://localhost:3011/api';
const nodeCount = positiveInt(args.nodes, 100);
const runs = positiveInt(args.runs, 5);
const nodeType = args.nodeType || 'gateway';
const shape = args.shape || 'chain';
const timeoutMs = positiveInt(args.timeoutMs, 60000);
const pollMs = positiveInt(args.pollMs, 100);

if (!['gateway', 'script'].includes(nodeType)) {
  fail(`--node-type must be gateway or script, got: ${nodeType}`);
}
if (!['chain', 'fanout'].includes(shape)) {
  fail(`--shape must be chain or fanout, got: ${shape}`);
}

const templateName = `Benchmark ${nodeType} ${shape} ${nodeCount} ${new Date().toISOString()}`;

main().catch((error) => {
  console.error(`[benchmark] failed: ${error?.message || error}`);
  process.exit(1);
});

async function main() {
  console.log(`[benchmark] API: ${apiBaseUrl}`);
  console.log(`[benchmark] node_type=${nodeType}, shape=${shape}, nodes=${nodeCount}, runs=${runs}`);

  const workflow = buildWorkflow(nodeCount, nodeType, shape);
  const template = await createTemplate({
    name: templateName,
    description: 'Immediate-node runtime benchmark generated by benchmark-immediate-nodes.mjs',
    group: 'benchmark',
    tags: ['benchmark', 'runtime', nodeType, shape],
    version_note: `nodes=${nodeCount}, node_type=${nodeType}, shape=${shape}`,
    nodes: workflow.nodes,
    edges: workflow.edges,
  });

  console.log(`[benchmark] template_id=${template.id}`);

  const results = [];
  for (let run = 1; run <= runs; run += 1) {
    const startedAt = performance.now();
    const started = await startTemplate(template.id, {
      mode: 'async',
      input: {
        benchmark: {
          run,
          node_count: nodeCount,
          node_type: nodeType,
          shape,
        },
      },
    });
    const acceptedAt = performance.now();
    const result = await waitForCompletion(started.instance_id, timeoutMs, pollMs);
    const completedAt = performance.now();
    const trace = await fetchJson(`${apiBaseUrl}/instances/${started.instance_id}/trace`);
    const completedNodes = Array.isArray(trace)
      ? trace.filter((event) => event.event_type === 'NODE_COMPLETED' || event.type === 'NODE_COMPLETED').length
      : null;

    const acceptedMs = acceptedAt - startedAt;
    const completionMs = completedAt - startedAt;
    const nodesPerSecond = nodeCount / (completionMs / 1000);

    const row = {
      run,
      instance_id: started.instance_id,
      status: result.status,
      accepted_ms: round(acceptedMs),
      completion_ms: round(completionMs),
      nodes_per_second: round(nodesPerSecond),
      completed_node_events_in_recent_trace: completedNodes,
    };
    results.push(row);
    console.log(
      `[benchmark] run=${run} status=${row.status} completion_ms=${row.completion_ms} nodes_per_second=${row.nodes_per_second}`,
    );
  }

  const completionValues = results.map((item) => item.completion_ms);
  const throughputValues = results.map((item) => item.nodes_per_second);
  const summary = {
    api_base_url: apiBaseUrl,
    template_id: template.id,
    node_type: nodeType,
    shape,
    nodes: nodeCount,
    runs,
    completion_ms: summarize(completionValues),
    nodes_per_second: summarize(throughputValues),
    results,
  };

  console.log('[benchmark] summary');
  console.log(JSON.stringify(summary, null, 2));
}

function buildWorkflow(count, type, workflowShape) {
  const nodes = [
    {
      id: 'start',
      type: 'custom',
      position: { x: 0, y: 0 },
      data: {
        nodeType: 'start',
        label: 'Start',
      },
    },
    {
      id: 'end',
      type: 'custom',
      position: { x: (count + 1) * 180, y: 0 },
      data: {
        nodeType: 'end',
        label: 'End',
        resultPath: 'data.benchmark',
      },
    },
  ];

  for (let index = 1; index <= count; index += 1) {
    nodes.splice(nodes.length - 1, 0, buildImmediateNode(index, type, workflowShape));
  }

  const edges = workflowShape === 'fanout'
    ? buildFanoutEdges(count)
    : buildChainEdges(count);

  return { nodes, edges };
}

function buildImmediateNode(index, type, workflowShape) {
  if (type === 'script') {
    return {
      id: `node_${index}`,
      type: 'custom',
      position: {
        x: workflowShape === 'fanout' ? 220 + (index % 20) * 80 : index * 180,
        y: workflowShape === 'fanout' ? Math.floor(index / 20) * 80 : 0,
      },
      data: {
        nodeType: 'script',
        label: `Script ${index}`,
        code: `return { index: ${index}, ok: true };`,
        outputPath: `benchmark.node_${index}`,
        scriptTimeoutMs: 1000,
      },
    };
  }

  return {
    id: `node_${index}`,
    type: 'custom',
    position: {
      x: workflowShape === 'fanout' ? 220 + (index % 20) * 80 : index * 180,
      y: workflowShape === 'fanout' ? Math.floor(index / 20) * 80 : 0,
    },
    data: {
      nodeType: 'gateway',
      label: `Gateway ${index}`,
      gatewayType: 'exclusive',
    },
  };
}

function buildChainEdges(count) {
  const edges = [];
  let source = 'start';
  for (let index = 1; index <= count; index += 1) {
    edges.push(defaultEdge(source, `node_${index}`, index));
    source = `node_${index}`;
  }
  edges.push(defaultEdge(source, 'end', count + 1));
  return edges;
}

function buildFanoutEdges(count) {
  const edges = [];
  for (let index = 1; index <= count; index += 1) {
    edges.push(defaultEdge('start', `node_${index}`, index));
    edges.push(defaultEdge(`node_${index}`, 'end', count + index));
  }
  return edges;
}

function defaultEdge(source, target, index) {
  return {
    id: `edge_${index}_${source}_${target}`,
    source,
    target,
    data: {
      isDefault: true,
    },
  };
}

async function createTemplate(payload) {
  return fetchJson(`${apiBaseUrl}/templates`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(payload),
  });
}

async function startTemplate(templateId, payload) {
  return fetchJson(`${apiBaseUrl}/templates/${templateId}/start`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(payload),
  });
}

async function waitForCompletion(instanceId, timeout, poll) {
  const deadline = Date.now() + timeout;
  let latest = null;
  while (Date.now() <= deadline) {
    latest = await fetchJson(`${apiBaseUrl}/instances/${instanceId}/result`);
    if (latest.status === 'COMPLETED' || latest.status === 'FAILED') {
      return latest;
    }
    await sleep(poll);
  }
  throw new Error(
    `instance ${instanceId} did not complete within ${timeout}ms; latest=${JSON.stringify(latest)}`,
  );
}

async function fetchJson(url, init) {
  const response = await fetch(url, init);
  const text = await response.text();
  const payload = text ? JSON.parse(text) : null;
  if (!response.ok) {
    throw new Error(`${url} returned ${response.status}: ${JSON.stringify(payload)}`);
  }
  return payload;
}

function summarize(values) {
  const sorted = [...values].sort((a, b) => a - b);
  return {
    min: round(sorted[0]),
    p50: round(percentile(sorted, 0.5)),
    p95: round(percentile(sorted, 0.95)),
    max: round(sorted[sorted.length - 1]),
    avg: round(sorted.reduce((sum, value) => sum + value, 0) / sorted.length),
  };
}

function percentile(sorted, p) {
  if (sorted.length === 0) return 0;
  const index = Math.min(sorted.length - 1, Math.ceil(sorted.length * p) - 1);
  return sorted[index];
}

function parseArgs(argv) {
  const parsed = {};
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--') continue;
    if (!arg.startsWith('--')) continue;
    const [rawKey, inlineValue] = arg.slice(2).split('=');
    const key = rawKey.replace(/-([a-z])/g, (_, char) => char.toUpperCase());
    parsed[key] = inlineValue ?? argv[index + 1];
    if (inlineValue === undefined) index += 1;
  }
  return parsed;
}

function positiveInt(value, fallback) {
  const parsed = Number.parseInt(String(value ?? ''), 10);
  return Number.isFinite(parsed) && parsed > 0 ? parsed : fallback;
}

function round(value) {
  return Math.round(value * 100) / 100;
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

function fail(message) {
  console.error(`[benchmark] ${message}`);
  process.exit(1);
}
