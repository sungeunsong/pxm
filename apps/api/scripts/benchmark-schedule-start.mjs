#!/usr/bin/env node

import { MongoClient } from 'mongodb';

const args = parseArgs(process.argv.slice(2));
const apiBaseUrl = args.apiBaseUrl || process.env.API_BASE_URL || 'http://localhost:3011/api';
const schedules = positiveInt(args.schedules, 10);
const intervalSeconds = positiveInt(args.intervalSeconds, 1);
const timeoutMs = positiveInt(args.timeoutMs, 60000);
const pollMs = positiveInt(args.pollMs, 500);
const printRuns = args.printRuns === 'true';
const forceDueInSeconds =
  args.forceDueInSeconds === undefined ? null : positiveInt(args.forceDueInSeconds, 1);

main().catch((error) => {
  console.error(`[schedule-benchmark] failed: ${error?.message || error}`);
  process.exit(1);
});

async function main() {
  const created = [];
  const startedAt = Date.now();

  console.log(`[schedule-benchmark] API: ${apiBaseUrl}`);
  console.log(`[schedule-benchmark] schedules=${schedules}, interval_seconds=${intervalSeconds}`);

  try {
    for (let index = 1; index <= schedules; index += 1) {
      const template = await createScheduleTemplate(index);
      created.push(template);
    }

    const forcedDueAt = forceDueInSeconds
      ? await forceBenchmarkSchedulesDue(created, forceDueInSeconds)
      : null;
    const createdAt = Date.now();

    console.log(`[schedule-benchmark] created_templates=${created.length}`);
    if (forcedDueAt) {
      console.log(`[schedule-benchmark] forced_due_at=${forcedDueAt.toISOString()}`);
    }

    await waitForScheduleRuns(created, timeoutMs, pollMs);
    const completedAt = Date.now();

    const statuses = await Promise.all(
      created.map((template) => fetchJson(`${apiBaseUrl}/templates/${template.id}/schedule/status`)),
    );
    const queueStats = await fetchJson(`${apiBaseUrl}/engine/queue/stats`);

    const runRows = statuses.map((status, index) => {
      const run = status.runs?.[0] || null;
      const job = status.job || null;
      return {
        template_id: created[index].id,
        schedule_job_id: job?.id || null,
        job_status: job?.status || null,
        next_run_at: job?.nextRunAt || null,
        last_run_at: job?.lastRunAt || null,
        run_status: run?.status || null,
        instance_id: run?.instanceId || null,
        fired_at: run?.firedAt || null,
        error: run?.error || null,
      };
    });

    const firedCount = runRows.filter((row) => row.run_status === 'STARTED').length;
    const failedCount = runRows.filter((row) => row.run_status === 'FAILED').length;

    console.log('[schedule-benchmark] summary');
    console.log(
      JSON.stringify(
        {
          schedules,
          interval_seconds: intervalSeconds,
          elapsed_ms: completedAt - startedAt,
          create_ms: createdAt - startedAt,
          wait_for_fire_ms: completedAt - createdAt,
          forced_due_at: forcedDueAt?.toISOString() || null,
          fired_count: firedCount,
          failed_count: failedCount,
          queue: {
            queued: queueStats.queued,
            running: queueStats.running,
            failed: queueStats.failed,
            oldest_queued_age_ms: queueStats.oldest_queued_age_ms,
          },
          ...(printRuns ? { runs: runRows } : {}),
        },
        null,
        2,
      ),
    );
  } finally {
    await Promise.allSettled(created.map((template) => disableSchedule(template.id)));
    if (created.length) {
      console.log(`[schedule-benchmark] disabled_schedules=${created.length}`);
    }
  }
}

async function createScheduleTemplate(index) {
  const name = `Schedule Benchmark ${new Date().toISOString()} #${index}`;
  return fetchJson(`${apiBaseUrl}/templates`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      name,
      description: 'Schedule Start benchmark generated by benchmark-schedule-start.mjs',
      group: 'benchmark',
      tags: ['benchmark', 'schedule-start'],
      version_note: `schedules=${schedules}, interval_seconds=${intervalSeconds}`,
      nodes: [
        {
          id: 'start',
          type: 'custom',
          position: { x: 0, y: 0 },
          data: {
            nodeType: 'start',
            label: 'Start',
            triggerType: 'schedule',
            scheduleEnabled: true,
            scheduleType: 'interval',
            intervalSeconds,
          },
        },
        {
          id: 'end',
          type: 'custom',
          position: { x: 240, y: 0 },
          data: {
            nodeType: 'end',
            label: 'End',
            resultPath: 'formData',
          },
        },
      ],
      edges: [{ id: 'start-end', source: 'start', target: 'end' }],
    }),
  });
}

async function waitForScheduleRuns(templates, timeout, poll) {
  const deadline = Date.now() + timeout;
  while (Date.now() <= deadline) {
    const statuses = await Promise.all(
      templates.map((template) => fetchJson(`${apiBaseUrl}/templates/${template.id}/schedule/status`)),
    );
    const ready = statuses.every((status) => status.runs?.some((run) => run.status === 'STARTED'));
    if (ready) return;
    await sleep(poll);
  }

  throw new Error(`not all schedules fired within ${timeout}ms`);
}

async function disableSchedule(templateId) {
  return fetchJson(`${apiBaseUrl}/templates/${templateId}/schedule/toggle`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ enabled: false }),
  });
}

async function forceBenchmarkSchedulesDue(templates, dueInSeconds) {
  const uri = process.env.MONGODB_URL || 'mongodb://127.0.0.1:27017/?replicaSet=rs0';
  const dbName = process.env.MONGO_DB_NAME || 'pxm_db';
  const client = new MongoClient(uri);
  const dueAt = new Date(Date.now() + dueInSeconds * 1000);
  const now = new Date().toISOString();

  try {
    await client.connect();
    const definitionIds = templates.map((template) => template.id);
    await client.db(dbName).collection('v2_schedule_jobs').updateMany(
      {
        definition_id: { $in: definitionIds },
      },
      {
        $set: {
          active: true,
          status: 'WAITING',
          next_run_at: dueAt.toISOString(),
          lock_owner: null,
          locked_until: null,
          updated_at: now,
        },
      },
    );
    return dueAt;
  } finally {
    await client.close();
  }
}

async function fetchJson(url, init) {
  const response = await fetch(url, init);
  const text = await response.text();
  const payload = text ? JSON.parse(text) : null;
  if (!response.ok) {
    throw new Error(`${url} returned ${response.status}: ${JSON.stringify(payload)}`);
  }
  return payload;
}

function parseArgs(argv) {
  const parsed = {};
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--') continue;
    if (!arg.startsWith('--')) continue;
    const [rawKey, inlineValue] = arg.slice(2).split('=');
    const key = rawKey.replace(/-([a-z])/g, (_, char) => char.toUpperCase());
    parsed[key] = inlineValue ?? argv[index + 1];
    if (inlineValue === undefined) index += 1;
  }
  return parsed;
}

function positiveInt(value, fallback) {
  const parsed = Number.parseInt(String(value ?? ''), 10);
  return Number.isFinite(parsed) && parsed > 0 ? parsed : fallback;
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}
